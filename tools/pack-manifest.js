#!/usr/bin/env node
/* Generates site/js/pack-manifest.js: which variety packs (site/js/data/x*.js) add generators to which topic, so
 * js/packs.js can load only the packs a worksheet needs instead of all of them (~5.6 MB).
 *
 *   node tools/pack-manifest.js     # or: npm run manifest   -> (re)write site/js/pack-manifest.js
 *
 * Re-run it after adding a pack or an SPM.extend call; `npm run check` fails while the file is stale. The scan is
 * static (regex over the source) and deliberately strict: every `SPM.extend(` must be a direct call with a literal
 * topic key – `SPM.extend('F1-1.2', …)` – otherwise it stops with an error rather than guess. (tools/check.js also
 * cross-checks the result against the SPM.extend calls the packs actually make when run.)
 */
const fs = require('fs');
const path = require('path');
const dataDir = path.join(__dirname, '..', 'site', 'js', 'data');
const outFile = path.join(__dirname, '..', 'site', 'js', 'pack-manifest.js');

/** scan the packs -> { manifest: { key: ['x1a', …] }, errors: [msg] } */
function scan() {
  const packs = fs.readdirSync(dataDir).filter((f) => /^x.*\.js$/.test(f)).sort();
  const manifest = {};
  const errors = [];
  for (const f of packs) {
    const pack = f.replace(/\.js$/, '');
    const src = fs.readFileSync(path.join(dataDir, f), 'utf8');
    const lineOf = (i) => src.slice(0, i).split('\n').length;
    // any other way of reaching extend (an alias, destructuring, SPM['extend'] …) would hide a registration
    const alias = /[^.\w]extend\s*\(|\{[^{}]*\bextend\b[^{}]*\}\s*=\s*SPM\b|=\s*SPM\s*\.\s*extend\b|\[\s*['"`]extend['"`]\s*\]/.exec(src);
    if (alias) errors.push(`${f}:${lineOf(alias.index)}: extend used other than as a direct SPM.extend('<key>', …) call`);
    const all = /\bSPM\s*\.\s*extend\s*\(/g;
    const literal = /^\s*(['"])([^'"`$\\]+)\1\s*,/;
    let m;
    let n = 0;
    while ((m = all.exec(src))) {
      const lit = literal.exec(src.slice(m.index + m[0].length, m.index + m[0].length + 80));
      if (!lit) {
        errors.push(`${f}:${lineOf(m.index)}: SPM.extend without a literal topic key`);
        continue;
      }
      const key = lit[2];
      if (!/^F\d-[\w.]+$/.test(key)) errors.push(`${f}:${lineOf(m.index)}: unexpected topic key '${key}'`);
      manifest[key] = manifest[key] || [];
      if (!manifest[key].includes(pack)) manifest[key].push(pack);
      n++;
    }
    if (!n) errors.push(`${f}: no SPM.extend('<key>', …) call found`);
  }
  return { manifest, errors };
}

/** the file's full text for a manifest (one topic per line, so diffs stay readable) */
function render(manifest) {
  const rows = Object.keys(manifest).map((k) => `    '${k}': [${manifest[k].map((p) => `'${p}'`).join(', ')}],`);
  return `/* GENERATED by tools/pack-manifest.js (npm run manifest) – do not edit by hand; \`npm run check\` fails when stale.
 * Topic key -> the variety packs (js/data/x*.js) that add generators to it via SPM.extend, so js/packs.js can load
 * only the packs the selected topics need. Topics that no pack extends are absent.
 */
(function (root) {
  'use strict';
  const SPM = (root.SPM = root.SPM || {});
  SPM.packManifest = {
${rows.join('\n')}
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

/** { ok, errors, expected, actual } – does site/js/pack-manifest.js match the packs? (used by tools/check.js) */
function status() {
  const { manifest, errors } = scan();
  const expected = render(manifest);
  let actual = null;
  try {
    actual = fs.readFileSync(outFile, 'utf8');
  } catch (e) {}
  return { ok: !errors.length && actual === expected, errors, manifest, expected, actual };
}

module.exports = { scan, render, status, outFile };

if (require.main === module) {
  const { manifest, errors } = scan();
  if (errors.length) {
    for (const e of errors) console.error(e);
    console.error('pack-manifest: not written (fix the errors above)');
    process.exit(1);
  }
  fs.writeFileSync(outFile, render(manifest));
  const packs = new Set([].concat(...Object.values(manifest)));
  console.log(`wrote ${path.relative(process.cwd(), outFile)}: ${Object.keys(manifest).length} topics, ${packs.size} packs`);
}
